#!/usr/bin/env node
// Index of every judged idea in a project: one line per research/idea folder
// with its date, verdict and the reason, so an agent (or the founder) can see
// in one file which roads are already closed before opening a new one.
//
// Works on both layouts:
//   idea-gates layout — <ideas>/<slug>/verdict.md (front-matter verdict:, reason_gate:)
//                        and gates.md (failed_gate:)
//   report layout      — <ideas>/<YYYY-MM-slug>/REPORT.md whose verdict is a line
//                        like "**Вердикт:** закрыто — <why>" or "Verdict: closed — <why>"
//
// Usage:
//   node scripts/ideas-index.mjs --ideas research --out research/IDEAS.md
//   node scripts/ideas-index.mjs --ideas brain/ideas            # print only
//
// Prints JSON (counts and folders without a readable verdict); --out writes the
// markdown table. Never edits the reports themselves.

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const args = {};
for (let i = 2; i < process.argv.length; i++) {
  const a = process.argv[i];
  if (a.startsWith('--')) args[a.slice(2)] = process.argv[++i];
}
if (!args.ideas) { console.error('Usage: ideas-index.mjs --ideas <dir> [--out IDEAS.md]'); process.exit(2); }

const WORDS = [
  [/(не\s+)?строить|build/i, 'build'],
  [/отлож|defer/i, 'defer'],
  [/закрыт|closed|no-go/i, 'closed'],
];
const RU = { build: 'строить', defer: 'отложить', closed: 'закрыто' };

function frontMatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  const fm = {};
  if (m) for (const line of m[1].split('\n')) {
    const kv = line.match(/^([\w-]+):\s*(.*?)\s*$/);
    if (kv) fm[kv[1]] = kv[2];
  }
  return fm;
}
function classify(text) {
  for (const [re, v] of WORDS) {
    const m = text.match(re);
    if (m && !(v === 'build' && m[1])) return v; // "не строить" is not build
  }
  return null;
}
const clean = s => s.replace(/\*\*/g, '').replace(/\s+/g, ' ').replace(/\|/g, '/').trim();

const rows = [];
const unreadable = [];
for (const d of readdirSync(args.ideas, { withFileTypes: true })) {
  if (!d.isDirectory() || d.name.startsWith('_') || d.name.startsWith('.')) continue;
  const dir = join(args.ideas, d.name);
  const verdictFile = join(dir, 'verdict.md');
  const reportFile = join(dir, 'REPORT.md');
  let title = d.name, verdict = null, why = '', date = (d.name.match(/^\d{4}-\d{2}(-\d{2})?/) || [''])[0];

  if (existsSync(verdictFile)) {
    const text = readFileSync(verdictFile, 'utf8');
    const fm = frontMatter(text);
    verdict = classify(fm.verdict || '');
    const gates = existsSync(join(dir, 'gates.md')) ? frontMatter(readFileSync(join(dir, 'gates.md'), 'utf8')) : {};
    why = fm.reason_gate || (gates.failed_gate && gates.failed_gate !== 'none' ? `gate ${gates.failed_gate}` : '');
    const card = join(dir, 'card.md');
    if (existsSync(card)) title = (readFileSync(card, 'utf8').match(/^#\s+(.+)$/m) || [, title])[1];
  } else if (existsSync(reportFile)) {
    const text = readFileSync(reportFile, 'utf8');
    title = (text.match(/^#\s+(.+)$/m) || [, title])[1];
    const dm = text.match(/\*\*Дата:\*\*\s*(\d{4}-\d{2}-\d{2})/) || text.match(/Date:\**\s*(\d{4}-\d{2}-\d{2})/i);
    if (dm) date = dm[1];
    // The last verdict line wins: the header often says "строить / отложить / закрыто"
    // as a template placeholder, the closing section holds the decision.
    const lines = text.split('\n');
    for (let i = lines.length - 1; i >= 0; i--) {
      const m = lines[i].match(/(?:Вердикт|Verdict)[^:]*:\**\s*(.*)$/i);
      if (!m) continue;
      let body = m[1];
      for (let j = i + 1; j < lines.length && lines[j].trim() && !/^#/.test(lines[j]); j++) body += ' ' + lines[j];
      body = clean(body);
      if (/строить\s*\/\s*отложить\s*\/\s*закрыто/i.test(body)) continue; // untouched template
      const v = classify(body.slice(0, 60));
      if (v) { verdict = v; why = body.replace(/^(не\s+)?(строить|отложить|закрыто|build|defer|closed)[\wа-яё]*\s*[—–:.-]?\s*/i, ''); break; }
    }
  }
  if (!verdict) { unreadable.push(d.name); continue; }
  rows.push({ date, folder: d.name, title: clean(title), verdict, why: why.length > 220 ? why.slice(0, 217) + '…' : why });
}

rows.sort((a, b) => b.date.localeCompare(a.date) || a.folder.localeCompare(b.folder));
const counts = rows.reduce((c, r) => (c[r.verdict] = (c[r.verdict] || 0) + 1, c), {});
console.log(JSON.stringify({ ideas: args.ideas, indexed: rows.length, counts, unreadable }, null, 2));

if (args.out) {
  const md = `# Ideas — what was judged and why

Generated by \`scripts/ideas-index.mjs\` (idea-gates) from \`${args.ideas}/\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand: change the report, then regenerate.
Read this before opening a new idea: a closed road stays closed unless the reason below no longer holds.

${Object.entries(counts).map(([v, n]) => `${RU[v]}: ${n}`).join(' · ')}${unreadable.length ? ` · без читаемого вердикта: ${unreadable.length}` : ''}

| date | idea | verdict | why |
|---|---|---|---|
${rows.map(r => `| ${r.date} | [${r.title}](${r.folder}/) | ${RU[r.verdict]} | ${r.why} |`).join('\n')}
${unreadable.length ? `\n## Без читаемого вердикта\n\n${unreadable.map(f => `- [${f}](${f}/)`).join('\n')}\n` : ''}`;
  writeFileSync(args.out, md);
  console.error(`Saved: ${args.out}`);
}
